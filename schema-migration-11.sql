-- ============================================================
-- 4) PAYMENT TRANSACTIONS (gateway abstraction + webhooks)
--    One payment can have many gateway transactions.
-- ============================================================
CREATE TABLE IF NOT EXISTS payment_transactions (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  payment_id INT UNSIGNED NOT NULL,
  user_id INT UNSIGNED NULL,
  booking_type VARCHAR(20) NOT NULL,
  booking_reference VARCHAR(30) NULL,
  gateway VARCHAR(50) NULL,
  transaction_type ENUM('authorize','capture','sale','refund','void','webhook') NOT NULL DEFAULT 'sale',
  transaction_reference VARCHAR(190) NULL,
  amount DECIMAL(10,2) NOT NULL DEFAULT 0,
  currency VARCHAR(3) NOT NULL DEFAULT 'USD',
  status ENUM('pending','processing','authorized','completed','failed','cancelled','refunded') NOT NULL DEFAULT 'pending',
  request_payload TEXT NULL,
  response_payload TEXT NULL,
  webhook_payload TEXT NULL,
  ip_address VARCHAR(45) NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_pt_payment FOREIGN KEY (payment_id) REFERENCES payments (id) ON DELETE CASCADE,
  INDEX idx_pt_payment (payment_id),
  INDEX idx_pt_reference (booking_reference),
  INDEX idx_pt_gateway_ref (gateway, transaction_reference)
) ENGINE=InnoDB;

-- ============================================================
-- 5) INVOICES (generic, reusable for all booking types)
-- ============================================================
CREATE TABLE IF NOT EXISTS invoices (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id INT UNSIGNED NOT NULL,
  booking_type ENUM('transfer','tour','hotel','room','event','taxi') NOT NULL,
  booking_id INT UNSIGNED NOT NULL,
  booking_reference VARCHAR(30) NULL,
  invoice_number VARCHAR(30) NOT NULL UNIQUE,
  subtotal DECIMAL(10,2) NOT NULL DEFAULT 0,
  tax_amount DECIMAL(10,2) NOT NULL DEFAULT 0,
  discount_amount DECIMAL(10,2) NOT NULL DEFAULT 0,
  total_amount DECIMAL(10,2) NOT NULL DEFAULT 0,
  currency VARCHAR(3) NOT NULL DEFAULT 'USD',
  status ENUM('draft','issued','paid','void','cancelled') NOT NULL DEFAULT 'draft',
  issued_at DATETIME NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_inv_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  INDEX idx_inv_user (user_id),
  INDEX idx_inv_booking (booking_type, booking_id),
  INDEX idx_inv_reference (booking_reference),
  INDEX idx_inv_status (status)
) ENGINE=InnoDB;

-- ============================================================
-- 6) BOOKING LOGS (audit timeline, generic for all types)
-- ============================================================
CREATE TABLE IF NOT EXISTS booking_logs (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  booking_type VARCHAR(20) NOT NULL,
  booking_id INT UNSIGNED NOT NULL,
  user_id INT UNSIGNED NULL,
  action VARCHAR(80) NOT NULL,
  description VARCHAR(255) NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_bl_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL,
  INDEX idx_bl_booking (booking_type, booking_id),
  INDEX idx_bl_user (user_id),
  INDEX idx_bl_action (action),
  INDEX idx_bl_created (created_at)
) ENGINE=InnoDB;

