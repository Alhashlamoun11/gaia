-- Objective: Create a single booking architecture that supports
--   * Tours   (GAIA-TO-XXXXXX)
--   * Hotels  (GAIA-HO-XXXXXX)
--   * Rooms   (GAIA-RO-XXXXXX)
--   * Events  (GAIA-EV-XXXXXX)
--   * Transfers (GAIA-TR-XXXXXX)
-- and will later connect to CyberSource WITHOUT requiring a
-- database redesign.
--
-- Implements:
--   * booking_reference column + unique index on EVERY booking table
--     (GAIA-* format, unique, auto-generated by BookingReferenceService)
--   * Expanded booking status ENUM on every booking table:
--       pending, awaiting_payment, paid, confirmed, completed,
--       cancelled, refunded
--   * payments table upgraded (booking_reference, payment_method,
--     gateway_response JSON, authorization_code, payment_token,
--     expanded status ENUM)
--   * payment_transactions table (gateway abstraction + webhooks)
--   * invoices table (generic, reusable for all booking types)
--   * booking_logs table (audit timeline)
--   * room_bookings table (Room booking type)
--   * user_id NOT NULL enforcement on all booking tables
--
-- NO CyberSource API integration. NO real payment processing.
-- Database + architecture preparation only.
--
-- Safe to run repeatedly (idempotent).
-- ============================================================
