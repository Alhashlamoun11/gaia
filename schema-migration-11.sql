-- ============================================================
-- 2) ROOM BOOKINGS (rooms) — GAIA-RO-XXXXXX
--    New table for the Room booking type.
-- ============================================================
CREATE TABLE IF NOT EXISTS room_bookings (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  booking_code VARCHAR(20) NOT NULL,
  booking_reference VARCHAR(30) NULL,
  hotel_id INT UNSIGNED NULL,
  room_id INT UNSIGNED NULL,
  user_id INT UNSIGNED NOT NULL,
  guest_name VARCHAR(150) NOT NULL,
  guest_email VARCHAR(150) NOT NULL,
  guest_phone VARCHAR(50) NULL,
  check_in_date DATE NOT NULL,
  check_out_date DATE NOT NULL,
  guests INT UNSIGNED NOT NULL DEFAULT 2,
  base_price DECIMAL(10,2) NOT NULL DEFAULT 0,
  nights INT UNSIGNED NOT NULL DEFAULT 1,
  discount DECIMAL(10,2) NOT NULL DEFAULT 0,
  total_price DECIMAL(10,2) NOT NULL DEFAULT 0,
  status ENUM('pending','awaiting_payment','paid','confirmed','completed','cancelled','refunded') NOT NULL DEFAULT 'pending',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_rb_hotel FOREIGN KEY (hotel_id) REFERENCES hotels (id) ON DELETE SET NULL,
  CONSTRAINT fk_rb_room FOREIGN KEY (room_id) REFERENCES hotel_rooms (id) ON DELETE SET NULL,
  CONSTRAINT fk_rb_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  UNIQUE KEY uq_rb_code (booking_code),
  UNIQUE KEY uq_rb_ref (booking_reference),
  INDEX idx_rb_user (user_id),
  INDEX idx_rb_email (guest_email),
  INDEX idx_rb_status (status)
) ENGINE=InnoDB;

